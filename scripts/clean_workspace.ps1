<#
.SYNOPSIS
    Cleans up temporary artifacts, old logs, orphan saves, scratch directories, and build outputs in Ether.

.DESCRIPTION
    Safely purges:
    - Orphan UUID saves (generated by headless tests/runs) while preserving canonical 'RUN-*' benchmark saves.
    - Temporary scratch directories and compiled scratch classes (e.g., scratch/scratch).
    - Rotated daily logs in logs/ (*.YYYY-MM-DD.log) while keeping the active society-simulation.log.
    - Export artifacts in exports/ (*.zip, *.csv).
    - Dist package artifacts in dist/ (optional or when -CleanDist / -All is specified).
    - Maven target/ build artifacts (when -CleanTarget / -All is specified).

.PARAMETER All
    Cleans all temporary workspaces (Saves, Scratch, Logs, Exports, Cache). Preserves canonical RUN-* saves.

.PARAMETER CleanSaves
    Removes orphan UUID saves and test saves in saves/, keeping canonical RUN-* scenarios intact.

.PARAMETER CleanScratch
    Removes the scratch/ directory contents, including scratch/scratch compiled classes and helper scripts.

.PARAMETER CleanLogs
    Removes rotated logs in logs/*.log while preserving the active log society-simulation.log.

.PARAMETER CleanExports
    Removes exported ZIP and CSV files from exports/.

.PARAMETER CleanDist
    Removes build and package distributions from dist/.

.PARAMETER CleanTarget
    Removes the Maven build directory target/.

.PARAMETER DryRun
    Outputs what files and directories would be removed without actually deleting them.

.EXAMPLE
    .\scripts\clean_workspace.ps1 -All
    .\scripts\clean_workspace.ps1 -CleanSaves -CleanLogs
    .\scripts\clean_workspace.ps1 -All -DryRun
#>

[CmdletBinding()]
param(
    [switch]$All,
    [switch]$CleanSaves,
    [switch]$CleanScratch,
    [switch]$CleanLogs,
    [switch]$CleanExports,
    [switch]$CleanDist,
    [switch]$CleanTarget,
    [switch]$DryRun
)

$ErrorActionPreference = "Continue"

$rootDir = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path "$rootDir\pom.xml")) {
    $rootDir = Get-Location
}

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "   Ether Scientific Platform - Workspace Cleanup Utility  " -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host "Workspace Root: $rootDir"
if ($DryRun) {
    Write-Host "[DRY RUN MODE ENABLED - No files will be deleted]" -ForegroundColor Yellow
}

$doSaves = $All -or $CleanSaves
$doScratch = $All -or $CleanScratch
$doLogs = $All -or $CleanLogs
$doExports = $All -or $CleanExports
$doDist = $CleanDist # Dist is only wiped if explicitly requested
$doTarget = $CleanTarget # Target is only wiped if explicitly requested

if (-not ($doSaves -or $doScratch -or $doLogs -or $doExports -or $doDist -or $doTarget)) {
    Write-Host "No cleanup switch specified. Defaulting to standard cleanup (-CleanSaves -CleanScratch -CleanLogs -CleanExports)." -ForegroundColor Yellow
    $doSaves = $true
    $doScratch = $true
    $doLogs = $true
    $doExports = $true
}

function Remove-SafeItem {
    param(
        [string]$Path,
        [string]$Description
    )
    if (Test-Path $Path) {
        if ($DryRun) {
            Write-Host "  [WOULD DELETE] $($Description): $Path" -ForegroundColor DarkYellow
        } else {
            try {
                Remove-Item -Path $Path -Recurse -Force -ErrorAction Stop
                Write-Host "  [DELETED] $($Description): $Path" -ForegroundColor Green
            } catch {
                Write-Host "  [ERROR] Failed to delete $($Path): $_" -ForegroundColor Red
            }
        }
    }
}

# 1. Clean Orphan & Test Saves
if ($doSaves) {
    Write-Host "`n[1/5] Inspecting saves/ directory..." -ForegroundColor White
    $savesDir = Join-Path $rootDir "saves"
    if (Test-Path $savesDir) {
        $dirs = Get-ChildItem -Directory -Path $savesDir
        $deletedCount = 0
        foreach ($d in $dirs) {
            # Target UUID folders or test/autosave folders, NEVER touch RUN-*
            $isUuid = $d.Name -match '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
            $isTestSave = $d.Name -like 'Test_Save_*' -or $d.Name -like 'AUTOSAVE_*' -or $d.Name -eq 'Autosave_Exit'
            
            if ($isUuid -or $isTestSave) {
                Remove-SafeItem -Path $d.FullName -Description "Orphan/Test Save"
                $deletedCount++
            }
        }
        Write-Host "  Evaluated $($dirs.Count) saves. Cleaned $deletedCount orphan/test directories." -ForegroundColor Gray
    } else {
        Write-Host "  saves/ directory does not exist." -ForegroundColor Gray
    }
}

# 2. Clean Scratch Directory
if ($doScratch) {
    Write-Host "`n[2/5] Inspecting scratch/ directory..." -ForegroundColor White
    $scratchDir = Join-Path $rootDir "scratch"
    if (Test-Path $scratchDir) {
        # Check for nested scratch/scratch
        $nestedScratch = Join-Path $scratchDir "scratch"
        if (Test-Path $nestedScratch) {
            Remove-SafeItem -Path $nestedScratch -Description "Nested scratch/scratch"
        }

        # Purge temporary scripts, compiled class files, and text dumps in scratch
        $scratchItems = Get-ChildItem -Path $scratchDir -Exclude "README.md"
        foreach ($item in $scratchItems) {
            Remove-SafeItem -Path $item.FullName -Description "Scratch artifact"
        }
    } else {
        Write-Host "  scratch/ directory does not exist." -ForegroundColor Gray
    }

    # Clean any root or child __pycache__
    $pycaches = Get-ChildItem -Path $rootDir -Directory -Recurse -Filter "__pycache__" -ErrorAction SilentlyContinue
    foreach ($py in $pycaches) {
        Remove-SafeItem -Path $py.FullName -Description "Python cache"
    }
}

# 3. Clean Logs and Subdirectory Caches
if ($doLogs) {
    Write-Host "`n[3/5] Inspecting logs/ directory and subdirectories..." -ForegroundColor White
    $logsDir = Join-Path $rootDir "logs"
    if (Test-Path $logsDir) {
        $totalFreedBytes = 0
        $cleanedFilesCount = 0

        # 3.1 Rotated daily logs in logs/*.log
        $rotatedLogs = Get-ChildItem -Path $logsDir -Filter "*.log" | Where-Object { $_.Name -match '\.\d{4}-\d{2}-\d{2}\.log$' }
        foreach ($log in $rotatedLogs) {
            $totalFreedBytes += $log.Length
            $cleanedFilesCount++
            Remove-SafeItem -Path $log.FullName -Description "Rotated daily log ($([math]::Round($log.Length / 1MB, 2)) MB)"
        }

        # 3.2 Heavy archives and scenario execution logs in logs/spatial_runs/
        $spatialDir = Join-Path $logsDir "spatial_runs"
        if (Test-Path $spatialDir) {
            $spatialFiles = Get-ChildItem -Path $spatialDir -File | Where-Object { $_.Name -like "*.tar.gz" -or $_.Name -like "*.log" }
            foreach ($f in $spatialFiles) {
                $totalFreedBytes += $f.Length
                $cleanedFilesCount++
                Remove-SafeItem -Path $f.FullName -Description "Spatial run artifact ($([math]::Round($f.Length / 1MB, 2)) MB)"
            }
        }

        # 3.3 Old batch logs in logs/gcp_batch/
        $gcpBatchDir = Join-Path $logsDir "gcp_batch"
        if (Test-Path $gcpBatchDir) {
            $gcpLogs = Get-ChildItem -Path $gcpBatchDir -Filter "*.log" -File
            foreach ($f in $gcpLogs) {
                $totalFreedBytes += $f.Length
                $cleanedFilesCount++
                Remove-SafeItem -Path $f.FullName -Description "GCP batch log ($([math]::Round($f.Length / 1MB, 2)) MB)"
            }
        }

        # 3.4 Execution logs in logs/windowed_validation/ (preserve reports *.md and *.json)
        $windowedDir = Join-Path $logsDir "windowed_validation"
        if (Test-Path $windowedDir) {
            $winLogs = Get-ChildItem -Path $windowedDir -Filter "*.log" -File
            foreach ($f in $winLogs) {
                $totalFreedBytes += $f.Length
                $cleanedFilesCount++
                Remove-SafeItem -Path $f.FullName -Description "Validation execution log ($([math]::Round($f.Length / 1MB, 2)) MB)"
            }
        }

        $mbFreed = [math]::Round($totalFreedBytes / 1MB, 2)
        Write-Host "  Cleaned $cleanedFilesCount log/archive files, freeing approximately $mbFreed MB." -ForegroundColor Gray
        Write-Host "  Preserved active log (society-simulation.log) and scientific benchmark reports." -ForegroundColor Cyan
    } else {
        Write-Host "  logs/ directory does not exist." -ForegroundColor Gray
    }
}

# 4. Clean Exports
if ($doExports) {
    Write-Host "`n[4/5] Inspecting exports/ directory..." -ForegroundColor White
    $exportsDir = Join-Path $rootDir "exports"
    if (Test-Path $exportsDir) {
        $exportFiles = Get-ChildItem -Path $exportsDir -File
        foreach ($f in $exportFiles) {
            Remove-SafeItem -Path $f.FullName -Description "Export archive/data ($($f.Extension))"
        }
    } else {
        Write-Host "  exports/ directory does not exist." -ForegroundColor Gray
    }
}

# 5. Clean Dist Staging & Packages
$distDir = Join-Path $rootDir "dist"
if (Test-Path $distDir) {
    # 5.1 Always clean unzipped staging directories (e.g., *-standalone/) which are temporary assembly folders
    $stagingDirs = Get-ChildItem -Path $distDir -Directory | Where-Object { $_.Name -like "*-standalone*" }
    if ($stagingDirs.Count -gt 0) {
        Write-Host "`n[Dist] Cleaning unzipped temporary staging directories in dist/..." -ForegroundColor White
        foreach ($d in $stagingDirs) {
            Remove-SafeItem -Path $d.FullName -Description "Unzipped dist staging directory ($($d.Name))"
        }
    }

    # 5.2 Clean distribution archives (.zip, .tar.gz) only if -CleanDist is explicitly requested
    if ($doDist) {
        Write-Host "`n[Optional] Purging distribution archives in dist/ (-CleanDist)..." -ForegroundColor White
        $distFiles = Get-ChildItem -Path $distDir -File
        foreach ($item in $distFiles) {
            Remove-SafeItem -Path $item.FullName -Description "Distribution archive package ($($item.Name))"
        }
    }
}

# 6. Clean Target (if requested)
if ($doTarget) {
    Write-Host "`n[Optional] Inspecting target/ directory..." -ForegroundColor White
    $targetDir = Join-Path $rootDir "target"
    if (Test-Path $targetDir) {
        Remove-SafeItem -Path $targetDir -Description "Maven build directory"
    }
}

Write-Host "`n==========================================================" -ForegroundColor Green
Write-Host "   Cleanup Complete! Workspace is sanitized and healthy.   " -ForegroundColor Green
Write-Host "==========================================================" -ForegroundColor Green
